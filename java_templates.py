import json


def content_java(project, materials):
    lines = []
    for name, mat in materials.items():
        kind = mat["kind"]
        if kind == "log":
            factory, props = "RotatedPillarBlock::new", "BlockBehaviour.Properties.ofFullCopy(Blocks.OAK_LOG)"
        elif kind == "leaves":
            factory = "p -> new LeavesBlock(AmbientLeavesBlockSoundPlayer.noAmbientSound(), p)"
            props = "BlockBehaviour.Properties.ofFullCopy(Blocks.OAK_LEAVES)"
        elif kind in {"plant", "tall"}:
            factory = "GroundPlant::new" if kind == "plant" else "DoublePlantBlock::new"
            props = "BlockBehaviour.Properties.ofFullCopy(Blocks.SHORT_GRASS)"
        elif kind == "grass":
            factory = "Block::new"
            # Deliberately static terrain. Do not inherit vanilla spreading that converts to vanilla dirt.
            props = "BlockBehaviour.Properties.of().strength(0.6F).sound(SoundType.GRASS).mapColor(MapColor.GRASS)"
        else:
            factory = "Block::new"
            vanilla = {"dirt": "DIRT", "stone": "STONE", "deepstone": "DEEPSLATE"}[kind]
            props = f"BlockBehaviour.Properties.ofFullCopy(Blocks.{vanilla})"
        lines.append(f'        register("{name}", {factory}, {props});')
    registrations = "\n".join(lines)
    return f'''// Generated by Biome Configurator Fabric. Regenerate through the app.
package {project.package};

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.function.Function;
import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.creativetab.v1.CreativeModeTabEvents;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.references.BlockItemId;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.CreativeModeTabs;
import net.minecraft.world.level.block.*;
import net.minecraft.world.level.block.sounds.AmbientLeavesBlockSoundPlayer;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.material.MapColor;

public final class GeneratedContent implements ModInitializer {{
    public static final Map<String, Block> BLOCKS = new LinkedHashMap<>();

    @Override public void onInitialize() {{
{registrations}
        CreativeModeTabEvents.modifyOutputEvent(CreativeModeTabs.NATURAL_BLOCKS).register(output ->
            BLOCKS.values().forEach(block -> output.accept(block.asItem())));
    }}

    private static void register(String name, Function<BlockBehaviour.Properties, Block> factory,
                                 BlockBehaviour.Properties properties) {{
        Identifier location = Identifier.fromNamespaceAndPath("{project.namespace}", name);
        if (BuiltInRegistries.BLOCK.containsKey(location)) {{
            throw new IllegalStateException("Biome Configurator block ID already registered: " + location);
        }}
        BlockItemId id = BlockItemId.create(location, location);
        Block block = factory.apply(properties.setId(id.block()));
        Registry.register(BuiltInRegistries.BLOCK, id.block(), block);
        Registry.register(BuiltInRegistries.ITEM, id.item(),
            new BlockItem(block, new Item.Properties().setId(id.item()).useBlockDescriptionPrefix()));
        BLOCKS.put(name, block);
    }}

    public static Block block(String name) {{
        Block block = BLOCKS.get(name);
        if (block == null) throw new IllegalStateException("Generated block not initialized: " + name);
        return block;
    }}

    // Uses vanilla vegetation survival checks, including the minecraft:dirt tag we extend.
    public static final class GroundPlant extends VegetationBlock {{
        public GroundPlant(BlockBehaviour.Properties properties) {{ super(properties); }}
    }}
}}
'''


def client_java(project, materials):
    lines = []
    for name, mat in materials.items():
        if mat["tinted"]:
            source = "foliage" if mat["kind"] == "leaves" else "grass"
            lines.append(f'        BlockColorRegistry.register(List.of(BlockTintSources.{source}()), GeneratedContent.block("{name}"));')
    registrations = "\n".join(lines)
    return f'''// Generated by Biome Configurator Fabric.
package {project.package};
import java.util.List;
import net.fabricmc.api.ClientModInitializer;
import net.fabricmc.fabric.api.client.rendering.v1.BlockColorRegistry;
import net.minecraft.client.color.block.BlockTintSources;

public final class GeneratedClient implements ClientModInitializer {{
    @Override public void onInitializeClient() {{
{registrations}
    }}
}}
'''


def worldgen_java(project, designs):
    registrations = []
    for biome, design in designs.items():
        base = design["base_biome"].split(":")[1].upper()
        registrations.append(f'''        Regions.register(new Region(id("bc_{biome}"), RegionType.OVERWORLD, {int(design['region_weight'])}) {{
            @Override public void addBiomes(Registry<Biome> registry,
                    Consumer<Pair<Climate.ParameterPoint, ResourceKey<Biome>>> mapper) {{
                addModifiedVanillaOverworldBiomes(mapper, builder ->
                    builder.replaceBiome(Biomes.{base}, ResourceKey.create(Registries.BIOME, id("{biome}"))));
            }}
        }});''')
    regions = "\n".join(registrations)
    return f'''// Generated by Biome Configurator Fabric. Uses TerraBlender's own region overlay.
package {project.package};
import com.mojang.datafixers.util.Pair;
import java.util.function.Consumer;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.Biomes;
import net.minecraft.world.level.biome.Climate;
import terrablender.api.MaterialRuleManager;
import terrablender.api.Region;
import terrablender.api.Regions;
import terrablender.api.RegionType;
import terrablender.api.TerraBlenderApi;

public final class GeneratedWorldgen implements TerraBlenderApi {{
    private static Identifier id(String path) {{
        return Identifier.fromNamespaceAndPath("{project.namespace}", path);
    }}
    @Override public void onTerraBlenderInitialized() {{
{regions}
        MaterialRuleManager.addRules(MaterialRuleManager.RuleCategory.OVERWORLD,
            "{project.namespace}", ResourceKey.create(Registries.MATERIAL_RULE, id("bc_surface")));
    }}
}}
'''


def surface_rule(project, designs):
    def block(name):
        return {"type": "minecraft:block", "result_state": f"{project.namespace}:{name}"}
    def condition(test, rule):
        return {"type": "minecraft:condition", "if_true": test, "then_run": rule}
    rules = ["minecraft:bedrock_floor"]
    for name, design in designs.items():
        ids = design["blocks"]
        ground = {"type": "minecraft:sequence", "sequence": [
            condition({"type": "minecraft:water", "offset": -1, "surface_depth_multiplier": 0, "add_stone_depth": False}, block(ids["grass"])),
            block(ids["dirt"]),
        ]}
        layers = {"type": "minecraft:sequence", "sequence": [
            condition({"type": "minecraft:stone_depth", "offset": 0, "add_surface_depth": False, "secondary_depth_range": 0, "surface_type": "floor"}, ground),
            condition({"type": "minecraft:stone_depth", "offset": 3, "add_surface_depth": False, "secondary_depth_range": 0, "surface_type": "floor"}, block(ids["dirt"])),
            condition({"type": "minecraft:vertical_gradient", "random_name": f"{project.namespace}:deepstone",
                       "true_at_and_below": {"absolute": int(design["deep_y"])},
                       "false_at_and_above": {"absolute": int(design["deep_y"]) + 8}}, block(ids["deepstone"])),
            block(ids["stone"]),
        ]}
        rules.append(condition({"type": "minecraft:biome", "biome_is": f"{project.namespace}:{name}"}, layers))
    rules.append("minecraft:overworld")
    return {"type": "minecraft:sequence", "sequence": rules}
